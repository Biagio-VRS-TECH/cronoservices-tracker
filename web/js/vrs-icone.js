/**
 * L'icona come stringa SVG, per chi costruisce l'HTML a mano.
 *   svgIcona('cestino')             → decorativa (aria-hidden)
 *   svgIcona('cestino', 16, 'Elimina') → con nome accessibile (role="img")
 */
export function svgIcona(nome, lato = 20, titolo = '') {
  const d = PERCORSI[nome];
  if (!d) throw new Error('icona sconosciuta: ' + nome);
  const t = String(titolo || '').replace(/[&<>"]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));
  return `<svg width="${lato}" height="${lato}" viewBox="0 0 24 24" fill="none" stroke="currentColor" ` +
    `stroke-width="${TRATTO}" stroke-linecap="round" stroke-linejoin="round" focusable="false" ` +
    (t ? `role="img"><title>${t}</title>` : 'aria-hidden="true">') +
    `<path d="${d}"/></svg>`;
}
